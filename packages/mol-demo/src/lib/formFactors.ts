export const FF: Record<string, readonly number[]> = {};
FF_SYMS.forEach((sym, i) => {
  FF[sym] = FF_DATA[i];
});

export const Q_MAX = 25.0;
export const Q_MIN = 0.01;
export const FF_N = 128;

// Must match the diffraction shader's atom-loop bound (cf. MAX_ATOMS_JS).
export const MAX_ATOMS_MOBILE = 16;
export const MAX_ATOMS_DESKTOP = 60;

export function maxAtoms(isMobile: boolean): number {
  return isMobile ? MAX_ATOMS_MOBILE : MAX_ATOMS_DESKTOP;
}

export const FF_TBL: Record<string, Float32Array> = {};
for (const sym of FF_SYMS) {
  const c = FF[sym];
  const t = new Float32Array(FF_N);
  for (let i = 0; i < FF_N; i++) {
    const q = Q_MIN + ((Q_MAX - Q_MIN) * i) / (FF_N - 1);
    const s = (q / (4 * Math.PI)) ** 2;
    t[i] =
      c[0] * Math.exp(-c[4] * s) +
      c[1] * Math.exp(-c[5] * s) +
      c[2] * Math.exp(-c[6] * s) +
      c[3] * Math.exp(-c[7] * s) +
      c[8];
  }
  FF_TBL[sym] = t;
}

// Interpolated form factor lookup; q is clamped to [Q_MIN, Q_MAX].
// Throws on unknown elements — callers must validate first (see validateMolecule).
export function ff(el: string, q: number): number {
  const tbl = FF_TBL[el];
  if (!tbl) throw new Error(`mol-demo: no form factors for element "${el}"`);
  const i = Math.max(
    0,
    Math.min(FF_N - 1, Math.round(((q - Q_MIN) / (Q_MAX - Q_MIN)) * (FF_N - 1))),
  );
  return tbl[i];
}
